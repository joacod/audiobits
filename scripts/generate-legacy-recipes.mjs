import { readFile, writeFile } from "node:fs/promises";
import prettier from "prettier";

// Build-time copies keep the transitional export independent of catalog at runtime.
const registry = JSON.parse(
  await readFile(new URL("../registry.json", import.meta.url), "utf8"),
);
const sources = [];
for (const item of registry.items.filter(
  (item) => item.meta.classification === "recipe",
)) {
  const file = item.files.find((file) => file.path.endsWith("/recipe.ts"));
  sources.push(
    (await readFile(new URL(`../${file.path}`, import.meta.url), "utf8"))
      .replace('import { defineSound, type Recipe } from "audiobits";\n', "")
      .replaceAll('Extract<Recipe, { kind: "one-shot" }>', "OneShotRecipe")
      .replaceAll('Extract<Recipe, { kind: "sustained" }>', "SustainedRecipe")
      .trim(),
  );
}
const path = new URL(
  "../packages/audiobits/src/recipes/index.ts",
  import.meta.url,
);
const generated = await prettier.format(
  `// Generated by scripts/generate-legacy-recipes.mjs. Edit catalog/recipes source.
import { defineSound } from "../recipe/validate";
import type { OneShotRecipe, SustainedRecipe } from "../recipe/generated";

${sources.join("\n\n")}
`,
  { parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== generated)
    throw new Error(
      "Legacy recipes drifted; run node scripts/generate-legacy-recipes.mjs",
    );
} else {
  await writeFile(path, generated);
}
