import { build } from "esbuild";
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { dirname, resolve, parse } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const destination = resolve(root, "skills/audiobits/scripts");
const check = process.argv.includes("--check");
const bundled = await build({
  absWorkingDir: root,
  entryPoints: ["tools/mcp/bundle.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  minify: true,
  charset: "utf8",
  legalComments: "eof",
  sourcemap: false,
  write: false,
  metafile: true,
  define: { AUDIOBITS_BUNDLED: "true" },
  external: ["audiobits", "audiobits/*"],
  banner: {
    js: "#!/usr/bin/env node\n// Generated by tools/mcp/build-skill.mjs. See mcp.LICENSE.txt for bundled licenses.",
  },
});

// Bundle only server dependencies. The consumer's runtime stays a dynamic import.
const packages = new Map();
for (const input of Object.keys(bundled.metafile.inputs)) {
  if (!input.includes("node_modules/")) continue;
  let directory = dirname(resolve(root, input));
  while (directory !== parse(directory).root) {
    let manifest;
    try {
      manifest = JSON.parse(
        await readFile(resolve(directory, "package.json"), "utf8"),
      );
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      directory = dirname(directory);
      continue;
    }
    if (!manifest.name) {
      directory = dirname(directory);
      continue;
    }
    if (manifest.name === "audiobits")
      throw new Error("AudioBits runtime must not be bundled.");
    const license = (await readdir(directory)).find((name) =>
      /^licen[cs]e(?:\.(?:txt|md))?$/i.test(name),
    );
    if (!license) throw new Error(`Missing bundled license: ${manifest.name}`);
    packages.set(
      manifest.name,
      `${manifest.name}@${manifest.version}\n${await readFile(resolve(directory, license), "utf8")}`,
    );
    break;
  }
}
for (const output of Object.values(bundled.metafile.outputs)) {
  for (const imported of output.imports) {
    if (
      !imported.path.startsWith("node:") &&
      !imported.path.startsWith("audiobits")
    ) {
      throw new Error(`Unbundled dependency: ${imported.path}`);
    }
  }
}
const executable = bundled.outputFiles[0].contents;
if (executable.length > 1024 * 1024)
  throw new Error("Skill MCP exceeds the 1 MiB executable budget.");
const outputs = new Map([
  ["mcp.mjs", executable],
  [
    "mcp.LICENSE.txt",
    Buffer.from(
      [...packages.entries()]
        .sort(([a], [b]) => a.localeCompare(b, "en"))
        .map(([, value]) => value)
        .join("\n\n---\n\n"),
    ),
  ],
]);
if (!check) await mkdir(destination, { recursive: true });
for (const [name, content] of outputs) {
  const path = resolve(destination, name);
  if (check) {
    const committed = await readFile(path).catch((error) => {
      if (error.code !== "ENOENT") throw error;
      return Buffer.alloc(0);
    });
    if (!committed.equals(Buffer.from(content)))
      throw new Error(`Stale Skill output: ${name}. Run pnpm build:skill.`);
  } else
    await writeFile(path, content, {
      mode: name === "mcp.mjs" ? 0o755 : 0o644,
    });
}
console.log(
  `Skill MCP ${check ? "synchronized" : "built"}: ${executable.length} bytes; ${packages.size} bundled dependency licenses.`,
);
